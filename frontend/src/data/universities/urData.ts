export function getURProgramme(id: string) {
  return UR_PROGRAMMES.find((programme) => programme.id === id);
}

export function getURProgrammesByCombination(combination: string) {
  const normalized = combination.trim().toUpperCase();

  return UR_PROGRAMMES.filter((programme) =>
    programme.combinations.some(
      (item) => item.toUpperCase() === normalized,
    ),
  );
}

export function getURDocumentsForRoute(route: URApplicantRoute) {
  return UR_DOCUMENTS.filter((document) =>
    document.requiredFor.includes(route),
  );
}
